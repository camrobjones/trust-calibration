#!/usr/bin/env python3
"""Regenerate the appendix sampled-questions frequency table from the trial CSVs.

Reads  stats/e{1..4}_trials.csv + ../data/conversation_Question.csv
Writes stats/appendix_question_freq.tex
Rerun after any change to the stats CSVs:  python3 make_question_freq_table.py
"""
import csv, collections

QUESTIONS = "../data/conversation_Question.csv"
TRIALS = ["stats/e%d_trials.csv" % i for i in range(1, 5)]
OUT = "stats/appendix_question_freq.tex"

qs = [r for r in csv.DictReader(open(QUESTIONS)) if int(r["id"]) <= 30]
# order: as in the appendix question tables — physics (by id), then logic, probability, facts
CAT_ORDER = ["physics", "logic", "probability", "facts"]
qs.sort(key=lambda r: (CAT_ORDER.index(r["subcategory"]), int(r["id"])))

counts = {}  # (exp, qid) -> {intro: n, final: n}
totals = collections.defaultdict(lambda: [0, 0])
present = collections.defaultdict(set)
for path in TRIALS:
    for r in csv.DictReader(open(path)):
        exp, qid, tt = r["experiment"], int(r["question_id"]), r["trial_type"]
        c = counts.setdefault((exp, qid), {"intro": 0, "final": 0})
        c[tt] += 1
        totals[exp]["intro final".split().index(tt)] += 1
        present[exp].add(qid)

exps = ["E1", "E2", "E3", "E4"]
unused_e4 = sorted(set(int(q["id"]) for q in qs) - present["E4"])
unused_names = [q["name"] for q in qs if int(q["id"]) in unused_e4]

lines = [
    "% Appendix: how often each question was sampled for the conversation phase, by experiment.",
    "% GENERATED by conversation/analysis/make_question_freq_table.py from stats/e{1..4}_trials.csv — do not hand-edit.",
    '% Cell format: intro-phase count / final-trial count. "--" = question not used in that experiment.',
    "",
    r"\begin{table}[p]",
    r"\centering",
    r"\caption{Number of times each question was selected for the conversation phase in each experiment, among trials included in the final analyses. Cells show intro-phase / final-trial counts. Questions were not sampled uniformly: on each conversation trial the question was selected based on the participant's own survey-phase responses (e.g., intro-phase questions on which the participant's confidence and accuracy allowed the advisor to argue for a correct or incorrect answer as required by the helpfulness condition, and a final question on which the advisor could argue against the participant's stated belief), so questions that participants tended to answer with particular confidence--accuracy profiles were sampled more or less often. Six questions (%s) were not used in Experiment 4.}" % ", ".join(unused_names),
    r"\label{tab:question-freq}",
    r"\footnotesize",
    r"\setlength{\tabcolsep}{5pt}",
    r"\begin{tabular}{llrrrr}",
    r"\toprule",
    r"Question & Category & E1 & E2 & E3 & E4 \\",
    r"\midrule",
]
for q in qs:
    qid = int(q["id"])
    cells = []
    for exp in exps:
        c = counts.get((exp, qid))
        cells.append("--" if c is None else f"{c['intro']} / {c['final']}")
    name = q["name"].replace("_", r"\_")
    lines.append(f"{name} & {q['subcategory'].capitalize()} & " + " & ".join(cells) + r" \\")
lines += [
    r"\midrule",
    "Total & & " + " & ".join(f"{totals[e][0]} / {totals[e][1]}" for e in exps) + r" \\",
    r"\bottomrule",
    r"\end{tabular}",
    r"\end{table}",
]
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"wrote {OUT}")
print("totals:", {e: totals[e] for e in exps})
print("E4 unused:", unused_names)
